"""
src/healthcare_ml.py
Healthcare Machine Learning Module for AegisEdge-Q.

Provides:
- Reproducible synthetic healthcare vital-signs dataset generation.
- Data validation and missing-value imputation.
- Leak-free preprocessing and train/test splitting pipeline.
- Classical Logistic Regression training and inference.
- Dynamic performance metric computation (accuracy, precision, recall, f1, roc_auc, confusion matrix).
- Input boundary checking and sanitized inference.

DISCLAIMER:
All datasets and models generated by this module are purely synthetic demonstrations
designed for algorithmic evaluation and educational prototyping. They do NOT represent
clinically validated diagnostic tools and must NEVER be used for real medical decision-making.
"""

from typing import Dict, Any, Tuple, Optional
import numpy as np
import pandas as pd
from sklearn.model_selection import train_test_split
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    roc_auc_score,
    confusion_matrix,
    roc_curve,
)

FEATURE_COLUMNS = ["age", "heart_rate", "systolic_bp", "body_temp"]

FEATURE_RANGES = {
    "age": (18.0, 95.0),
    "heart_rate": (40.0, 180.0),
    "systolic_bp": (80.0, 220.0),
    "body_temp": (35.0, 41.5),
}


def generate_synthetic_healthcare_data(
    n_samples: int = 1200,
    random_state: int = 42,
    introduce_missing: bool = False,
    missing_ratio: float = 0.02,
) -> pd.DataFrame:
    """
    Generate a reproducible synthetic healthcare dataset.

    Features:
    - age: Patient age in years [18 - 85]
    - heart_rate: Resting heart rate in beats per minute [50 - 130]
    - systolic_bp: Systolic blood pressure in mmHg [90 - 190]
    - body_temp: Core body temperature in Celsius [36.0 - 39.5]

    Ground-truth Label Rule:
    A continuous risk propensity score is calculated as a calibrated weighted combination
    of elevated vitals (hypertension, tachycardia, pyrexia, advanced age) plus logistic sigmoid
    activation with stochastic Gaussian noise. This models clinical cardiovascular/metabolic
    instability without using real patient records.

    Label:
    - 0: Normal / Low Risk
    - 1: Elevated Clinical Risk Indicator
    """
    rng = np.random.default_rng(random_state)

    age = rng.integers(18, 85, size=n_samples).astype(float)
    heart_rate = rng.normal(loc=76.0, scale=14.0, size=n_samples)
    heart_rate = np.clip(heart_rate, 48.0, 145.0)

    systolic_bp = rng.normal(loc=124.0, scale=18.0, size=n_samples)
    systolic_bp = np.clip(systolic_bp, 85.0, 205.0)

    body_temp = rng.normal(loc=36.8, scale=0.6, size=n_samples)
    body_temp = np.clip(body_temp, 35.5, 40.2)

    # Documented synthetic risk rule (z-score weighted clinical indicator)
    # Elevated age (>60), high BP (>140), high HR (>100), fever (>38.0)
    risk_score = (
        0.04 * (age - 50.0)
        + 0.03 * (heart_rate - 75.0)
        + 0.045 * (systolic_bp - 120.0)
        + 1.8 * (body_temp - 37.0)
        + rng.normal(0.0, 0.6, size=n_samples)
    )

    # Convert to probability via sigmoid function
    risk_prob = 1.0 / (1.0 + np.exp(-risk_score))
    risk_label = (risk_prob >= 0.5).astype(int)

    df = pd.DataFrame(
        {
            "age": age,
            "heart_rate": heart_rate,
            "systolic_bp": systolic_bp,
            "body_temp": body_temp,
            "high_risk": risk_label,
        }
    )

    if introduce_missing and missing_ratio > 0:
        for col in FEATURE_COLUMNS:
            mask = rng.random(size=n_samples) < missing_ratio
            df.loc[mask, col] = np.nan

    return df


def build_ml_pipeline(random_state: int = 42) -> Pipeline:
    """
    Construct a scikit-learn pipeline consisting of median imputation,
    standard scaling, and logistic regression.
    """
    return Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", StandardScaler()),
            (
                "classifier",
                LogisticRegression(
                    solver="lbfgs",
                    C=1.0,
                    max_iter=1000,
                    random_state=random_state,
                ),
            ),
        ]
    )


def train_and_evaluate_model(
    df: pd.DataFrame,
    test_size: float = 0.25,
    random_state: int = 42,
) -> Dict[str, Any]:
    """
    Train a classical Logistic Regression model using strict train/test splitting
    to avoid data leakage, and dynamically calculate all validation metrics.
    """
    X = df[FEATURE_COLUMNS]
    y = df["high_risk"]

    X_train, X_test, y_train, y_test = train_test_split(
        X,
        y,
        test_size=test_size,
        random_state=random_state,
        stratify=y,
    )

    pipeline = build_ml_pipeline(random_state=random_state)
    pipeline.fit(X_train, y_train)

    y_pred = pipeline.predict(X_test)
    y_prob = pipeline.predict_proba(X_test)[:, 1]

    cm = confusion_matrix(y_test, y_pred)
    fpr, tpr, _ = roc_curve(y_test, y_prob)

    metrics = {
        "accuracy": float(accuracy_score(y_test, y_pred)),
        "precision": float(precision_score(y_test, y_pred, zero_division=0)),
        "recall": float(recall_score(y_test, y_pred, zero_division=0)),
        "f1": float(f1_score(y_test, y_pred, zero_division=0)),
        "roc_auc": float(roc_auc_score(y_test, y_prob)),
        "confusion_matrix": cm.tolist(),
        "n_train": len(X_train),
        "n_test": len(X_test),
        "roc_fpr": fpr.tolist(),
        "roc_tpr": tpr.tolist(),
    }

    # Extract learned coefficients
    classifier = pipeline.named_steps["classifier"]
    coefs = dict(zip(FEATURE_COLUMNS, [float(c) for c in classifier.coef_[0]]))
    intercept = float(classifier.intercept_[0])

    return {
        "pipeline": pipeline,
        "metrics": metrics,
        "coefficients": coefs,
        "intercept": intercept,
        "X_test": X_test,
        "y_test": y_test,
        "y_pred": y_pred,
        "y_prob": y_prob,
    }


def validate_patient_input(inputs: Dict[str, float]) -> Tuple[bool, Optional[str]]:
    """
    Validate that user-provided vital inputs fall within physiologically plausible boundaries.
    """
    for feature in FEATURE_COLUMNS:
        if feature not in inputs:
            return False, f"Missing vital sign feature: '{feature}'"
        val = inputs[feature]
        if not isinstance(val, (int, float)) or np.isnan(val):
            return False, f"Invalid value for '{feature}': Must be a numeric value."
        min_val, max_val = FEATURE_RANGES[feature]
        if val < min_val or val > max_val:
            return (
                False,
                f"Value for '{feature}' ({val}) is outside plausible demonstration range [{min_val}, {max_val}].",
            )
    return True, None


def predict_patient_risk(
    pipeline: Pipeline, inputs: Dict[str, float]
) -> Dict[str, Any]:
    """
    Generate an inference prediction for an individual patient's vitals.
    Returns predicted risk class, probability, and risk severity tier.
    """
    is_valid, error_msg = validate_patient_input(inputs)
    if not is_valid:
        raise ValueError(error_msg)

    input_df = pd.DataFrame([{col: float(inputs[col]) for col in FEATURE_COLUMNS}])
    predicted_class = int(pipeline.predict(input_df)[0])
    probabilities = pipeline.predict_proba(input_df)[0]
    risk_prob = float(probabilities[1])

    if risk_prob < 0.35:
        tier = "Low Clinical Risk Indicator"
        recommendation = "Demonstration indicates vitals within nominal baseline ranges."
    elif risk_prob < 0.65:
        tier = "Moderate Clinical Risk Indicator"
        recommendation = "Demonstration shows borderline elevation across several vitals."
    else:
        tier = "Elevated Clinical Risk Indicator"
        recommendation = "Demonstration indicates high risk propensity across vital signs."

    return {
        "predicted_class": predicted_class,
        "risk_probability": risk_prob,
        "confidence": float(max(probabilities)),
        "risk_tier": tier,
        "recommendation": recommendation,
        "disclaimer": "SYNTHETIC DEMONSTRATION ONLY: Not a medical diagnosis. Do not use for clinical care.",
    }
